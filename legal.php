         Regulation (EU) 2019/1150.</p>
      </br>

      <h3>5. Dispute resolution &amp; ODR</h3>
      <p>Disputes about a transaction concern the buyer and the seller directly. For consumers resident in the EU,
         the European Commission provides an Online Dispute Resolution (ODR) platform:
         <a href="https://ec.europa.eu/consumers/odr" target="_blank" rel="noopener">https://ec.europa.eu/consumers/odr</a>.
         Users may also seek mediation before the competent bodies. The platform will cooperate in good faith
         to facilitate communication between the parties.</p>
      </br>

      <h3>6. Right of withdrawal (consumers)</h3>
      <p>Where a consumer concludes a distance contract with a professional seller, EU consumer law may grant a
         <strong>14-day right of withdrawal</strong>. Because contracts are concluded directly with the seller,
         the right of withdrawal is exercised <strong>towards the seller</strong>, who must inform the consumer
         of the conditions, exceptions and procedure. All on Wheel Ltd, acting only as intermediary, is not the
         counterparty to these contracts. Contracts between businesses (B2B) are generally not covered by the
         consumer right of withdrawal.</p>

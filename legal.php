      <h3>3. Ranking criteria (Regulation EU 2019/1150 - P2B)</h3>
      <p>When suppliers, listings and rental offers are shown in search, browse or directory results,
         their order (ranking) is determined mainly by the following parameters, in decreasing order of importance:</p>
      <ul class="templatemo_list">
        <li><strong>Relevance to the request:</strong> match between the vehicle family/type or category selected by the user and the supplier's declared products/typologies.</li>
        <li><strong>Account tier:</strong> the supplier's plan (<em>Gold</em>, then <em>Premium</em>, then <em>Free</em>) and premium listings are shown before free ones. The tier is a <strong>paid feature</strong>: purchasing a higher tier improves visibility and ranking.</li>
        <li><strong>Completeness of the profile/listing:</strong> profiles and listings with more complete and accurate information may rank higher.</li>
        <li><strong>Recency:</strong> more recently published or updated content may rank higher.</li>
      </ul>
      <p>No third party pays for individual placement other than through the published tiers above.
         The main parameters and the reason for their relative importance are disclosed here in accordance
         with Article 5 of Regulation (EU) 2019/1150.</p>
      </br>

